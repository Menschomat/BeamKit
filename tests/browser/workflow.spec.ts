import { test, expect } from '@playwright/test';

test('generate, export, reject malformed import, undo, restore, and work offline', async ({ page, context }) => {
  page.on('pageerror', error => console.log('PAGE ERROR', error.message));
  page.on('console', message => { if (message.type() === 'error') console.log('CONSOLE', message.text()); });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Export STL' })).toBeEnabled();
  const depth = page.getByRole('spinbutton', { name: 'Depth', exact: true });
  await depth.fill('15');
  await expect(page.getByRole('button', { name: 'Export STL' })).toBeEnabled();
  const jsonDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save JSON' }).click();
  const json = await jsonDownload;
  const file = await json.path();
  expect(file).toBeTruthy();
  await page.getByRole('button', { name: 'Reset preset' }).click();
  await expect(depth).toHaveValue('12');
  await page.locator('input[type=file]').setInputFiles(file!);
  await expect(depth).toHaveValue('15');
  await page.locator('input[type=file]').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"format":"wrong"}') });
  await expect(page.getByRole('alert')).toContainText('Unsupported');
  await expect(depth).toHaveValue('15');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(depth).toHaveValue('12');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(depth).toHaveValue('15');
  await expect(page.getByRole('button', { name: 'Export STL' })).toBeEnabled();
  const stlDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export STL' }).click();
  expect((await stlDownload).suggestedFilename()).toBe('p96l-honeycomb.stl');
  await expect(page.getByRole('status')).toContainText('Offline ready');
  await expect(page.getByRole('status')).toContainText('Saved locally');
  await context.setOffline(true);
  await page.reload();
  await expect(depth).toHaveValue('15');
  await expect(page.getByRole('button', { name: 'Export STL' })).toBeEnabled();
  await depth.fill('18');
  await expect(page.getByRole('button', { name: 'Export STL' })).toBeEnabled();
});
